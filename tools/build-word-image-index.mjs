import { readdir, writeFile } from 'node:fs/promises'

const assetDir = new URL('../public/assets/word-learning/generated/', import.meta.url)
const output = new URL('../src/wordImages.generated.ts', import.meta.url)
const files = (await readdir(assetDir))
  .filter((name) => name.endsWith('.webp'))
  .map((name) => name.slice(0, -5))
  .sort()
await writeFile(output, `// Generated by tools/build-word-image-index.mjs. Do not edit by hand.\nexport const wordImageFiles:ReadonlySet<string>=new Set(${JSON.stringify(files)})\n`)
console.log(`Word images: indexed ${files.length} files`)
